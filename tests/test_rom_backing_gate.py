def test_target_passes_on_the_real_fixture():
    """Healthy repo: the control arm is accepted and the violation refused.

    Half the pair. This one fails a gate that refuses everything — including
    one that refuses the control arm — so a green violation arm cannot be
    reached by a rule with no discrimination in it.
    """
    r = make("rom-unbacked")
    assert r.returncode == 0, (
        f"make rom-unbacked failed on the real tree:\n{r.stdout}\n{r.stderr}")
    assert "rom-unbacked OK" in r.stdout


def test_target_goes_RED_when_the_rule_is_removed(tmp_path):
    """THE plant. De-teeth the rule; `make rom-unbacked` must now fail.

    The other half of the pair, and the only evidence that can distinguish a
    verdict from a constant. `make toy-bad` shipped for a day exiting non-zero
    on every path, and seven consumers read only that status; a gate nobody has
    seen fail is not a gate.

    Plants into allocator/no_literals.py itself rather than into the fixture,
    because the fixture is the INPUT the gate reads — removing its claim sites
    is what the violation arm already does. What is unproven without this test
    is that the RULE, not the fixture, produces the verdict. Restored in a
    finally, and the module holds the repo lock.
    """
    src = ALLOC / "no_literals.py"
    original = src.read_text()
    call = "        all_findings += scan_rom_backing(paths, raw_map, map_path, stats, root)"
    assert call in original, "the plant site moved — update this test"
    try:
        src.write_text(original.replace(call, "    pass  # DE-TEETHED (test)"))
        r = make("rom-unbacked")
    finally:
        src.write_text(original)
    assert r.returncode != 0, (
        "make rom-unbacked SUCCEEDED with the backing rule removed — the "
        f"target's status is a constant, not a verdict:\n{r.stdout}\n{r.stderr}")
    assert "no teeth" in r.stdout


