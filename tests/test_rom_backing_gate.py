# The two gate-LIST rows use a regex rather than a literal, because the list
# legitimately grows: `time-check` joined it on 2026-08-06 and turned both
# literals into false reds that said "rom-unbacked is missing" about a line
# that contained rom-unbacked. What is being asserted is MEMBERSHIP of the
# list, not its exact spelling — a test that breaks whenever a sibling gate
# is added trains people to edit the test instead of reading it.
@pytest.mark.parametrize("path,needle,what", [
    ("Makefile", re.compile(r"^push:(?:\s+[\w-]+)*\s+rom-unbacked\b", re.M),
     "`make push`'s prerequisites — the documented front door"),
    ("tools/git-hooks/pre-push",
     re.compile(r"^for gate in(?:\s+[\w-]+)*\s+rom-unbacked\b", re.M),
     "the pre-push hook's gate loop"),
    # There was a fourth row here — the hosted workflow's own step. The
    # workflow was retired on 2026-08-22 and the row went with the file it
    # read. The surface it stood for is now `make gates` (and `make
    # bare-check`, which runs the gate block inside its clone), which reaches
    # `rom-unbacked` through the `gates:` list rather than a restated step.
    ("tools/setup.sh", "make rom-unbacked",
     "tools/setup.sh's bring-up proof on a fresh clone"),
])
def test_rom_unbacked_is_wired_where_toy_bad_is(path, needle, what):
    """docs/37 §4 and AGENTS.md both present this gate as toy-bad's
    presence-side twin. It landed wired into `make gates` and into `make test`
    only — so the surfaces a human and a fresh clone actually go through did
    not run it. A doc calling two gates twins while one of them
    runs in half the places is the shape this test exists to stop.

    Textual on purpose: running `make push` would push, and running the hook
    would need a remote. What is being checked is the WIRING, and the wiring
    is text in these three files.
    """
    text = (SUPERFORGE / path).read_text()
    assert "toy-bad" in text, f"{path}: toy-bad's own wiring moved — update this test"
    hit = needle.search(text) if hasattr(needle, "search") else (needle in text)
    assert hit, f"rom-unbacked is missing from {what} ({path})"


