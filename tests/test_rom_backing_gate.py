def test_no_shipping_asm_narrates_a_chunk_count():
    """The in-tree guard. Every claim site takes the emitted count.

    This used to say "and mode7_stream's per-chunk MVN stub table, the same
    narration one step downstream". That stub table no longer names chunk
    symbols by template: the blob-binding retrofit (an earlier phase a later sweep) made
    mode7_stream blob-agnostic, and the name cannot enter a feature file
    because `scan_blanket_rom_template` refuses any `ES_R_...%s` form. The
    table now reads `.repeat M7S_CHUNKS` / `.byte $54, $7E, M7S_BLOB_BANK +
    CI`, with the count still DERIVED — the includer binds
    `M7S_CHUNKS = ::ES_R_WORLD_MAP_CHUNKS`.

    STATED LIMIT that trade opened: an includer that binds a NARRATED
    `M7S_CHUNKS = 8` is not visible to `scan_chunk_count_narration`, which
    looks for a `.repeat <literal>` with a templated body in ONE file. The
    binding and the `.repeat` are now in different files by construction.
    """
    import re as _re
    roots = [SUPERFORGE / "game", SUPERFORGE / "engine", SUPERFORGE / "vendor" / "probes",
             SUPERFORGE / "tests" / "fixtures" / "rom_backing"]
    checked = 0
    for root in roots:
        for f in sorted(root.rglob("*.asm")):
            fs = no_literals.scan_chunk_count_narration(
                f, f.read_text().splitlines())
            checked += 1
            assert not fs, "\n".join(str(x) for x in fs)
    assert checked > 20, f"only {checked} .asm scanned — the roots moved"
    # ...and the guard is armed: the tree HAS templated chunk sites to narrate.
    # Three files, and they are the three that SHOULD have them — the two real
    # claim sites beside their `.incbin` (microzero's main.asm, the vendored
    # col_map probe) plus the backed fixture. It was four until mode7_stream
    # stopped naming a blob (see the docstring); the bound was lowered with
    # that removal rather than left to be met by an unrelated file.
    hits = sorted(str(f.relative_to(SUPERFORGE))
                  for root in roots for f in root.rglob("*.asm")
                  if _re.search(r'ES_R_[A-Z_]*_T%d', f.read_text()))
    assert len(hits) >= 3, f"only {hits} templated chunk site(s) — guard disarmed"


# --------------------------------------------------------------------------
# scanned is not assembled
# --------------------------------------------------------------------------
#
# THE SEMANTICS CHOSEN. A claim site credits a claim only if it lives in a file
# ca65 actually assembles into THIS composition — the `.include` closure of the
# translation unit's root. The root is the first positional file (`--asm-root`
# overrides); the closure is resolved by BASENAME against the scanned list,
# because `.include "scene_mgr.asm"` is resolved by ca65 against a `-I` set
# this tool never receives.
#
# Why that shape: the gate's promise is "something includes these bytes into
# THIS rom". What it checked was "some .asm somewhere in the argument list
# mentions the symbol", and the argument list comes from a Makefile wildcard
# over ALL of engine/features. For microzero the two differ by 9 files.
#
# Error direction: a wrong root collapses the closure and every claim reads
# UNBACKED — a loud refusal, never a silent pass.

def test_a_claim_site_in_an_UNASSEMBLED_file_does_not_credit(tmp_path):
    """The unassembled-file arm, end to end.

    Delete microzero's grad_tabs claim site (arm A: refused), then add the
    identical four lines in a file the composition never `.include`s. Before
    this change that arm went GREEN — a claim credited by a file contributing
    no bytes, reachable through the Makefile's own wildcard over
    engine/features.
    """
    mz = SUPERFORGE / "game" / "microzero"
    race = (mz / "scenes" / "race.asm").read_text().splitlines()
    lo = next(i for i, l in enumerate(race) if "gradient_tabs.bin" in l)
    site = race[lo - 1:lo + 3]                       # label, .incbin, asserts
    assert any("ES_R_GRAD_TABS" in l for l in site), site
    stripped = tmp_path / "race.asm"
    stripped.write_text("\n".join(race[:lo - 1] + race[lo + 3:]) + "\n")

    others = ([mz / "main.asm"]
              + [p for p in sorted((mz / "scenes").glob("*.asm"))
                 if p.name != "race.asm"]
              + sorted((SUPERFORGE / "engine" / "features").glob("*/*.asm")))
    mp = SUPERFORGE / "build" / "mz" / "symbol_map.json"

    a = gate(mp, mz / "main.asm", stripped, *others[1:])
    assert a.returncode == 1 and "ES_R_GRAD_TABS'" in a.stderr, (
        f"arm A did not reproduce the bug:\n{a.stdout}{a.stderr}")

    # arm B: the same four lines, in a file nothing .includes
    orphan = tmp_path / "never_included.asm"
    orphan.write_text("\n".join(site) + "\n")
    b = gate(mp, mz / "main.asm", stripped, *others[1:], orphan)
    assert b.returncode == 1 and "ES_R_GRAD_TABS'" in b.stderr, (
        "a claim site in a file the composition never .includes CREDITED the "
        f"claim — scanned is still being read as assembled:\n{b.stdout}{b.stderr}")


