def test_empty_backed_by_is_refused_by_the_schema(tmp_path):
    """An exemption that need not say why is a quiet way to turn the rule off.

    Same convention as `; REG-LINT: ok — <reason>` and `; WIDTH-LINT: ok —
    <reason>`, enforced where the declaration is parsed rather than where it is
    read, so it cannot be smuggled past a gate that happens not to run.
    """
    p = tmp_path / "feature.toml"
    p.write_text('name = "x"\nrole = "blob"\n\n'
                 '[[claims.rom]]\nname = "y"\nbytes = 16\nbacked_by = "  "\n')
    sub = schemas.load_substrate(ALLOC / "substrate.toml")
    with pytest.raises(schemas.SchemaError) as e:
        schemas.load_feature(p, sub)
    assert "backed_by" in str(e.value) and "empty" in str(e.value)


def test_backed_by_reaches_the_symbol_map(tmp_path):
    """The gate reads the MAP, not feature.toml — so the declaration has to
    survive the allocator. Emitted on rom placements only; a `backed_by` key on
    40 non-rom placements reads like a field someone forgot to fill."""
    out = tmp_path / "m"
    r = subprocess.run(
        [sys.executable, str(ALLOC / "allocate.py"),
         "--game", str(FIXTURE), "--out", str(out)],
        cwd=SUPERFORGE, capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    d = json.loads((out / "symbol_map.json").read_text())
    roms = {p["sym"]: p for p in d["globals"] if p["class"] == "rom"}
    assert roms["ES_R_FIXTURE_EXTERN"]["backed_by"].strip()
    assert roms["ES_R_FIXTURE_BLOB"]["backed_by"] == ""
    assert all("backed_by" not in p for p in d["globals"] if p["class"] != "rom")


