"""The rom-claim BACKING gate (docs/37) — the target, the rule, the limits.

WHAT THIS GATE IS FOR. A `rom` claim reserves bytes; it does not put any there.
The allocator packs it and emits `ES_R_<NAME>_{BANK,ADDR,OFF,SIZE}`, and the
claim site in ASM ties its `.incbin` to those symbols with
`.assert ^label = ES_R_<NAME>_BANK` — so a claim DRIFTING away from its data is
refused at assembly time. Nothing ever asked the other question: does the claim
have any data at all.

The bug that proves it matters is not hypothetical. rgb_gradient's `grad_tabs`
during an earlier breaker build (2026-08-02) was generated by its asset tool,
prerequisited in the Makefile and packed by the allocator, and **no .asm file
ever included it**. Three HDMA channels streamed the neighbouring blob's bytes
as COLDATA. The only symptom was a missing backdrop wash, and `make register`,
`no_literals`, `width-check`, the allocator's own packing and the full pytest
suite were all green.

TWO LAYERS, BOTH TESTED, following tests/test_make_gates.py's discipline: the
`make rom-unbacked` TARGET (where the wiring lives — the two arms, the greps,
the polarity) and the RULE inside `no_literals` (where the semantics live).

WHAT PINS THE TEETH IS A PAIR, NOT EITHER TEST ALONE. A gate that refuses
everything and a gate that refuses nothing are both useless, and each passes
one half of the pair:

  * `test_target_passes_on_the_real_fixture` fails a refuse-everything gate;
  * `test_target_goes_RED_when_the_rule_is_removed` fails a refuse-nothing one.

Together they force the verdict to be a function of the tree.
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

SUPERFORGE = Path(__file__).resolve().parent.parent
FIXTURE = SUPERFORGE / "tests" / "fixtures" / "rom_backing"
ALLOC = SUPERFORGE / "allocator"

sys.path.insert(0, str(ALLOC))
import no_literals  # noqa: E402
import schemas      # noqa: E402

# The target tests run whole gates over the live tree and one plants into
# allocator/no_literals.py, so they take the repo lock the other whole-gate
# module takes (tests/conftest.py).
pytestmark = pytest.mark.usefixtures("repo_tree_lock")


def make(*args) -> subprocess.CompletedProcess:
    """A target exactly as CI, tools/setup.sh and a human invoke it.

    MAKEFLAGS cleared for the reason tests/test_make_gates.py states: under
    `make test` these become recursive makes and would otherwise inherit any
    flag the outer invocation carried.
    """
    env = {k: v for k, v in os.environ.items()
           if k not in ("MAKEFLAGS", "MFLAGS", "MAKELEVEL")}
    return subprocess.run(["make", *args], cwd=SUPERFORGE,
                          capture_output=True, text=True, env=env)


def gate(map_path: Path, *files) -> subprocess.CompletedProcess:
    """Positional args pass straight through, so a test can hand in a flag
    (`--partial-files`) as well as paths."""
    return subprocess.run(
        [sys.executable, str(ALLOC / "no_literals.py"), "--map", str(map_path),
         *[str(f) for f in files]],
        cwd=SUPERFORGE, capture_output=True, text=True)


@pytest.fixture(scope="module")
def fixture_map(tmp_path_factory) -> Path:
    out = tmp_path_factory.mktemp("romgate")
    r = subprocess.run(
        [sys.executable, str(ALLOC / "allocate.py"),
         "--game", str(FIXTURE), "--out", str(out)],
        cwd=SUPERFORGE, capture_output=True, text=True)
    assert r.returncode == 0, f"fixture allocation failed:\n{r.stdout}{r.stderr}"
    return out / "symbol_map.json"


